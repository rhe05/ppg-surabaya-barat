  public.sub_kelp, public.jamaah, public.jamaah_acara, public.jamaah_kehadiran
  TO service_role;

ALTER TABLE public.sub_kelp         ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jamaah           ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jamaah_acara     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jamaah_kehadiran ENABLE ROW LEVEL SECURITY;

