--   EXISTS (SELECT 1 FROM auth_profile()
--             p(role, scope_ppg_id, scope_desa_id, scope_kelompok_id, guru_id, is_active)
--           WHERE p.is_active AND (
--                p.role = 'admin_ppg'
--             OR (p.role = 'admin_desa'  AND p.scope_desa_id =
--                   (SELECT k.desa_id FROM kelompok k WHERE k.id = <K>))
--             OR (p.role = 'admin_kelompok' AND p.scope_kelompok_id = <K>)
--             OR (p.role = 'penerobos'      AND p.scope_kelompok_id = <K>)))
