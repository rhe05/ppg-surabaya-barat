-- Fitur "Penerobos Kelp" (Pnb Kelp) -- data & kehadiran majlis taklim
-- jamaah keluarga/umum. Empat tabel:
--
--   sub_kelp          -- pembagian dalam satu kelompok ("Sub Kelp"), tiap
--                        sub-kelp punya nama. Analog "kelas" pada generus.
--   jamaah            -- data jamaah (mirip santri/guru, tapi dewasa:
--                        tanpa jenjang/kelas ngaji; + pekerjaan, status
--                        dalam keluarga).
--   jamaah_acara      -- satu pertemuan/pengajian (judul + tanggal +
--                        tempat). Kehadiran dicatat PER ACARA.
--   jamaah_kehadiran  -- status hadir/izin/sakit/alpa per jamaah per acara.
--
-- Cakupan akses = satu kelompok. Peran baru 'penerobos' (migrasi
-- 20260909150000 -- WAJIB dijalankan lebih dulu) mengelola penuh
-- kelompoknya; admin_kelompok / admin_desa / admin_ppg ikut bisa (pola
-- persis tabel santri).
--
-- Idempoten: CREATE TABLE/INDEX IF NOT EXISTS, DROP POLICY/TRIGGER IF
-- EXISTS sebelum CREATE. Aman dijalankan ulang.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- Tabel
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.sub_kelp (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kelompok_id bigint NOT NULL REFERENCES public.kelompok (id),
  nama        text   NOT NULL,
  keterangan  text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  deleted_at  timestamptz
);
CREATE INDEX IF NOT EXISTS sub_kelp_kelompok_idx
  ON public.sub_kelp (kelompok_id) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS public.jamaah (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kelompok_id         bigint NOT NULL REFERENCES public.kelompok (id),
  sub_kelp_id         bigint REFERENCES public.sub_kelp (id),
  nama                text   NOT NULL,
  nama_panggilan      text,
  gender              public.gender_type,
  tempat_lahir        text,
  tanggal_lahir       date,
  status_keluarga     text,      -- Kepala Keluarga / Istri / Anak Dewasa / Lajang / Umum
  pekerjaan           text,
  pendidikan_terakhir text,
  no_wa               text,
  alamat              text,
  rt                  text,
  rw                  text,
  kelurahan           text,
  kecamatan           text,
  kabupaten_kota      text,
  provinsi            text,
  kode_pos            text,
  catatan             text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  deleted_at          timestamptz
);
CREATE INDEX IF NOT EXISTS jamaah_kelompok_idx
  ON public.jamaah (kelompok_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS jamaah_sub_kelp_idx
  ON public.jamaah (sub_kelp_id) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS public.jamaah_acara (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kelompok_id bigint NOT NULL REFERENCES public.kelompok (id),
  sub_kelp_id bigint REFERENCES public.sub_kelp (id),  -- NULL = gabungan se-kelompok
  judul       text   NOT NULL,
  tanggal     date   NOT NULL,
  tempat      text,
  keterangan  text,
  dibuat_oleh uuid REFERENCES public.profiles (id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  deleted_at  timestamptz
);
CREATE INDEX IF NOT EXISTS jamaah_acara_kelompok_tanggal_idx
  ON public.jamaah_acara (kelompok_id, tanggal DESC) WHERE deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS public.jamaah_kehadiran (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  acara_id    bigint NOT NULL REFERENCES public.jamaah_acara (id) ON DELETE CASCADE,
  jamaah_id   bigint NOT NULL REFERENCES public.jamaah (id),
  status      public.absensi_status NOT NULL,
  catatan     text,
  dicatat_oleh uuid REFERENCES public.profiles (id),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (acara_id, jamaah_id)
);
CREATE INDEX IF NOT EXISTS jamaah_kehadiran_acara_idx  ON public.jamaah_kehadiran (acara_id);
CREATE INDEX IF NOT EXISTS jamaah_kehadiran_jamaah_idx ON public.jamaah_kehadiran (jamaah_id);

-- ---------------------------------------------------------------------
-- updated_at (pakai fungsi bersama public.set_updated_at())
-- ---------------------------------------------------------------------
DROP TRIGGER IF EXISTS trg_sub_kelp_updated_at        ON public.sub_kelp;
DROP TRIGGER IF EXISTS trg_jamaah_updated_at          ON public.jamaah;
DROP TRIGGER IF EXISTS trg_jamaah_acara_updated_at    ON public.jamaah_acara;
DROP TRIGGER IF EXISTS trg_jamaah_kehadiran_updated_at ON public.jamaah_kehadiran;
CREATE TRIGGER trg_sub_kelp_updated_at        BEFORE UPDATE ON public.sub_kelp        FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER trg_jamaah_updated_at          BEFORE UPDATE ON public.jamaah          FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER trg_jamaah_acara_updated_at    BEFORE UPDATE ON public.jamaah_acara    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER trg_jamaah_kehadiran_updated_at BEFORE UPDATE ON public.jamaah_kehadiran FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ---------------------------------------------------------------------
-- Hak akses tabel (RLS yang membatasi baris; grant ini cuma "boleh
