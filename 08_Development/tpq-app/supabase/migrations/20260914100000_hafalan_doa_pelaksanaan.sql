CREATE POLICY "hafalan_doa_select_scoped" ON public.hafalan_doa_pelaksanaan
  AS PERMISSIVE FOR SELECT TO authenticated
  USING (EXISTS ( SELECT 1
    FROM auth_profile() p(role, scope_ppg_id, scope_desa_id, scope_kelompok_id, guru_id, is_active)
    WHERE (p.is_active AND (
         (p.role = 'admin_ppg'::text)
      OR ((p.role = 'admin_desa'::text) AND (p.scope_desa_id = ( SELECT k.desa_id FROM kelompok k WHERE (k.id = hafalan_doa_pelaksanaan.kelompok_id))))
      OR ((p.role = 'admin_kelompok'::text) AND (p.scope_kelompok_id = hafalan_doa_pelaksanaan.kelompok_id))
      OR ((p.role = 'guru'::text) AND (p.guru_id IS NOT NULL) AND (EXISTS ( SELECT 1 FROM kelas kl
           WHERE ((kl.id = hafalan_doa_pelaksanaan.kelas_id) AND ((p.guru_id = kl.guru_id) OR (p.guru_id = kl.guru_id_2))))))
      OR ((p.role = 'pengunjung'::text) AND (p.guru_id IS NOT NULL) AND (EXISTS ( SELECT 1 FROM kelas kl
           WHERE ((kl.id = hafalan_doa_pelaksanaan.kelas_id) AND ((p.guru_id = kl.guru_id) OR (p.guru_id = kl.guru_id_2)))))
           AND public.pengunjung_masih_berlaku())
    ))));

