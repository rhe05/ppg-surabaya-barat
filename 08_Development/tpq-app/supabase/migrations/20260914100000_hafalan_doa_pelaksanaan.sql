CREATE TABLE IF NOT EXISTS public.hafalan_doa_pelaksanaan (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kelas_id     bigint NOT NULL REFERENCES public.kelas (id),
  kelompok_id  bigint NOT NULL REFERENCES public.kelompok (id),
  santri_id    bigint NOT NULL REFERENCES public.santri (id),
  tanggal      date NOT NULL,
  doa          text,
  status       text CHECK (status IS NULL OR status IN ('naik', 'tetap')),
  dibuat_oleh  uuid REFERENCES public.profiles (id),
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (santri_id, tanggal)
);
COMMENT ON TABLE public.hafalan_doa_pelaksanaan IS
  'Catatan Hafalan Do''a-Do''a Harian per santri per tanggal (Do''a / Naik|Tetap) -- diisi guru di kartu "Hafalan Do''a-Do''a Harian" pada Pelaksanaan Pembelajaran.';

CREATE INDEX IF NOT EXISTS idx_hafalan_doa_kelas_tanggal
  ON public.hafalan_doa_pelaksanaan (kelas_id, tanggal);

-- kelompok_id selalu ditimpa dari kelas (tidak dipercaya dari klien),
-- pola sama sync_hafalan_surat_kelompok_id.
CREATE OR REPLACE FUNCTION public.sync_hafalan_doa_kelompok_id()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  v_kelompok_id bigint;
BEGIN
  SELECT kl.kelompok_id INTO v_kelompok_id FROM public.kelas kl WHERE kl.id = NEW.kelas_id;
  IF v_kelompok_id IS NULL THEN
    RAISE EXCEPTION 'hafalan_doa_pelaksanaan.kelas_id % tidak ada di tabel kelas', NEW.kelas_id;
  END IF;
  NEW.kelompok_id = v_kelompok_id;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_hafalan_doa_sync_kelompok_id ON public.hafalan_doa_pelaksanaan;
CREATE TRIGGER trg_hafalan_doa_sync_kelompok_id
  BEFORE INSERT OR UPDATE OF kelas_id, kelompok_id ON public.hafalan_doa_pelaksanaan
  FOR EACH ROW EXECUTE FUNCTION public.sync_hafalan_doa_kelompok_id();

DROP TRIGGER IF EXISTS trg_hafalan_doa_updated_at ON public.hafalan_doa_pelaksanaan;
CREATE TRIGGER trg_hafalan_doa_updated_at
  BEFORE UPDATE ON public.hafalan_doa_pelaksanaan
