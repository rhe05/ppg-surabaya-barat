-- ---------------------------------------------------------------------
-- Helper: siapa penghimpun Shodaqoh -- SECURITY DEFINER, kolam TERPISAH
-- dari adalah_penghimpun() milik Tabungan (jangan disatukan).
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.adalah_penghimpun_shodaqoh(p_kelompok_id bigint)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = 'public'
AS $$
  SELECT EXISTS (
    SELECT 1
      FROM public.shodaqoh_penghimpun sp,
           auth_profile() p(role, scope_ppg_id, scope_desa_id, scope_kelompok_id, guru_id, is_active)
     WHERE sp.kelompok_id = p_kelompok_id
       AND sp.guru_id IS NOT NULL
       AND p.is_active
       AND p.role = 'guru'
       AND p.guru_id = sp.guru_id
       AND p.scope_kelompok_id = p_kelompok_id
  )
$$;
REVOKE ALL ON FUNCTION public.adalah_penghimpun_shodaqoh(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.adalah_penghimpun_shodaqoh(bigint) TO authenticated;

