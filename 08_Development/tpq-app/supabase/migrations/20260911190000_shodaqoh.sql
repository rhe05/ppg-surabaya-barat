-- nonaktifkan sendiri) -- owner beri contoh: "Shodaqoh Generus Sakit",
-- "Shodaqoh Guru Sakit", "Shodaqoh Generus Khitan", "Shodaqoh Tali Asih
-- Guru", tapi TIDAK dikunci ke daftar itu.
--
-- Owner memutuskan (2 pertanyaan klarifikasi):
--   1. Granularitas per JENIS, bukan seragam semua: tiap jenis punya
--      `mode` sendiri -- 'per_santri' (siapa nyumbang berapa, pola sama
--      tabungan_transaksi) ATAU 'global' (total terkumpul per kelas per
--      tanggal, pola sama infaq_pengajian).
--   2. Penghimpun Shodaqoh TERPISAH dari penghimpun Tabungan -- kolam
--      uang beda, bisa ditunjuk guru yang berbeda.
--
-- 4 tabel (pola SAMA PERSIS Tabungan, cuma TANPA arah 'tarik' -- shodaqoh
-- searah masuk, tidak ada mekanisme tarik-kembali spt tabungan):
--   shodaqoh_jenis       -- nama + mode, admin_kelompok kelola penuh.
--   shodaqoh_penghimpun  -- 1 baris per kelompok (kolam terpisah dari
--                           tabungan_penghimpun).
--   shodaqoh_setoran     -- guru serahkan himpunannya ke penghimpun.
--   shodaqoh_transaksi   -- satu baris kontribusi. mode 'per_santri' ->
--                           santri_id WAJIB; mode 'global' -> santri_id
--                           NULL, kelas_id opsional (NULL = se-kelompok).
-- =====================================================================

