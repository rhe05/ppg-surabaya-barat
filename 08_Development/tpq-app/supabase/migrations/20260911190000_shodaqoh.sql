CREATE TABLE IF NOT EXISTS public.shodaqoh_jenis (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kelompok_id  bigint NOT NULL REFERENCES public.kelompok (id),
  nama         text   NOT NULL,
  mode         text   NOT NULL CHECK (mode IN ('per_santri', 'global')),
  urutan       int    NOT NULL DEFAULT 99,
  aktif        boolean NOT NULL DEFAULT true,
  dibuat_oleh  uuid REFERENCES public.profiles (id),
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS shodaqoh_jenis_kelompok_idx
  ON public.shodaqoh_jenis (kelompok_id) WHERE aktif = true;

CREATE TABLE IF NOT EXISTS public.shodaqoh_penghimpun (
  kelompok_id  bigint PRIMARY KEY REFERENCES public.kelompok (id),
  guru_id      bigint REFERENCES public.guru (id),
  catatan      text,
  updated_oleh uuid REFERENCES public.profiles (id),
  updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.shodaqoh_setoran (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kelompok_id  bigint NOT NULL REFERENCES public.kelompok (id),
  guru_id      bigint NOT NULL REFERENCES public.guru (id),
  jumlah       integer NOT NULL CHECK (jumlah >= 0),
  tanggal      date NOT NULL,
  keterangan   text,
  dicatat_oleh uuid REFERENCES public.profiles (id),
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS shodaqoh_setoran_kelompok_idx
  ON public.shodaqoh_setoran (kelompok_id, tanggal DESC);

CREATE TABLE IF NOT EXISTS public.shodaqoh_transaksi (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kelompok_id  bigint NOT NULL REFERENCES public.kelompok (id),
  jenis_id     bigint NOT NULL REFERENCES public.shodaqoh_jenis (id),
  kelas_id     bigint REFERENCES public.kelas (id),   -- NULL = se-kelompok (mode global)
  santri_id    bigint REFERENCES public.santri (id),  -- WAJIB kalau jenis.mode = 'per_santri'
  jumlah       integer NOT NULL CHECK (jumlah >= 0),
  tanggal      date NOT NULL,
  keterangan   text,
  setoran_id   bigint REFERENCES public.shodaqoh_setoran (id) ON DELETE SET NULL,
  dicatat_oleh uuid REFERENCES public.profiles (id),
  dicatat_guru_id bigint REFERENCES public.guru (id),
  created_at   timestamptz NOT NULL DEFAULT now(),
  deleted_at   timestamptz
);
CREATE INDEX IF NOT EXISTS shodaqoh_transaksi_kelompok_idx
  ON public.shodaqoh_transaksi (kelompok_id, tanggal DESC) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS shodaqoh_transaksi_santri_idx
  ON public.shodaqoh_transaksi (santri_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS shodaqoh_transaksi_setoran_idx
  ON public.shodaqoh_transaksi (setoran_id);

DROP TRIGGER IF EXISTS trg_shodaqoh_jenis_updated_at ON public.shodaqoh_jenis;
