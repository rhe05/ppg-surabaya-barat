-- INSERT: admin bebas; guru boleh kalau --
--   mode per_santri (santri_id terisi): dia guru kelas santri itu
--     (termasuk guru gilir kedua) ATAU dia penghimpun Shodaqoh (cara 2,
--     langsung ke penghimpun tanpa lewat guru kelas -- sama pola
--     tabungan cara 2).
--   mode global (santri_id NULL): kelas_id NULL (se-kelompok, guru
--     mana pun di kelompok itu boleh) ATAU kelas_id terisi & dia guru
--     kelas itu.
DROP POLICY IF EXISTS "shodaqoh_transaksi_insert" ON public.shodaqoh_transaksi;
CREATE POLICY "shodaqoh_transaksi_insert" ON public.shodaqoh_transaksi
  AS PERMISSIVE FOR INSERT TO public
  WITH CHECK (EXISTS ( SELECT 1
    FROM auth_profile() p(role, scope_ppg_id, scope_desa_id, scope_kelompok_id, guru_id, is_active)
    WHERE (p.is_active AND (
         (p.role = 'admin_ppg'::text)
      OR ((p.role = 'admin_desa'::text) AND (p.scope_desa_id = ( SELECT k.desa_id FROM kelompok k WHERE (k.id = shodaqoh_transaksi.kelompok_id))))
      OR ((p.role = 'admin_kelompok'::text) AND (p.scope_kelompok_id = shodaqoh_transaksi.kelompok_id))
      OR ((p.role = 'guru'::text) AND (p.scope_kelompok_id = shodaqoh_transaksi.kelompok_id) AND (
           (shodaqoh_transaksi.santri_id IS NOT NULL AND (
             EXISTS ( SELECT 1 FROM santri s JOIN kelas k ON (k.id = s.kelas_id)
               WHERE (s.id = shodaqoh_transaksi.santri_id) AND ((p.guru_id = k.guru_id) OR (p.guru_id = k.guru_id_2)) AND (k.deleted_at IS NULL))
             OR public.adalah_penghimpun_shodaqoh(shodaqoh_transaksi.kelompok_id)
           ))
        OR (shodaqoh_transaksi.santri_id IS NULL AND (
             shodaqoh_transaksi.kelas_id IS NULL
             OR EXISTS ( SELECT 1 FROM kelas kl
               WHERE (kl.id = shodaqoh_transaksi.kelas_id) AND ((p.guru_id = kl.guru_id) OR (p.guru_id = kl.guru_id_2)))
           ))
      ))
    ))));

